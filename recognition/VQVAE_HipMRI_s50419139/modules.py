"""
modules.py
==========
Model definitions for the HipMRI 2D generative-modelling project (PyTorch only;
no NumPy in this file, as required by the specification).

Three networks are defined:

1. VQVAE  (main model)
   Encoder -> vector quantiser -> decoder (van den Oord et al., 2017).
   The encoder maps a 1 x 256 x 128 slice to a 64-dim vector at every cell of a
   32 x 16 grid (3 stride-2 downsamplings). Each vector is replaced by its
   nearest entry in a learned codebook of 512 vectors, so an image becomes a
   32 x 16 grid of integer codes. The decoder rebuilds the image from the
   quantised vectors.

   The codebook is updated with exponential moving averages (EMA) of the encoder
   outputs assigned to each code (paper Appendix A.1) instead of a codebook
   loss term; this is more stable and less prone to unused ("dead") codes.
   Two further guards against codebook collapse (found during testing: an
   untrained model sent every position to one code, perplexity 1.0):
   the codebook is initialised from real encoder outputs on the first training
   batch, and any code not selected for `restart_patience` consecutive
   training steps (default 50) is restarted at a random encoder output from
   the current batch. (A first version restarted codes only once their EMA
   usage decayed below 1, which took ~400 steps; a smoke test showed the
   codebook collapsing to one code within 10 steps, long before that.)
   The commitment loss beta * ||z_e - sg[e]||^2 (beta = 0.25) keeps encoder
   outputs close to their chosen codes. Gradients pass through the
   non-differentiable nearest-neighbour lookup with the straight-through
   estimator: z_q = z_e + sg[z_q - z_e].

2. VAE  (baseline)
   Same encoder/decoder backbone, but the latent is a continuous Gaussian with
   8 channels on the same 32 x 16 grid. Trained with reconstruction + KL loss.
   New images are generated by decoding z ~ N(0, I).

3. GatedPixelCNN  (prior over VQ-VAE codes)
   An autoregressive model of the 32 x 16 code grids (van den Oord et al.,
   2016, "Conditional Image Generation with PixelCNN Decoders"). Separate
   vertical and horizontal stacks remove the "blind spot" of the original
   PixelCNN. Sampling a code grid from it and decoding with the VQ-VAE decoder
   produces a new synthetic slice.

Run `python modules.py` for a quick CPU self-test (shapes, parameter counts,
and a check that the PixelCNN never looks at future positions).
"""

import torch
import torch.nn as nn
import torch.nn.functional as F


# --------------------------------------------------------------------------- #
# Shared building blocks
# --------------------------------------------------------------------------- #
class ResidualBlock(nn.Module):
    """ReLU -> 3x3 conv -> ReLU -> 1x1 conv, added back to the input."""

    def __init__(self, channels: int, hidden: int):
        super().__init__()
        self.block = nn.Sequential(
            nn.ReLU(),
            nn.Conv2d(channels, hidden, kernel_size=3, padding=1, bias=False),
            nn.ReLU(),
            nn.Conv2d(hidden, channels, kernel_size=1, bias=False),
        )

    def forward(self, x):
        return x + self.block(x)


class ResidualStack(nn.Module):
    def __init__(self, channels: int, hidden: int, n_blocks: int):
        super().__init__()
        self.blocks = nn.Sequential(*[ResidualBlock(channels, hidden) for _ in range(n_blocks)])

    def forward(self, x):
        return F.relu(self.blocks(x))


def _stage_channels(hidden: int, n_down: int) -> list:
    """Channel width after each downsampling, e.g. hidden=128, n_down=3 -> [32, 64, 128]."""
    return [max(hidden // 2 ** (n_down - 1 - i), 16) for i in range(n_down)]


class Encoder(nn.Module):
    """Image (B, C, H, W) -> feature map (B, out_channels, H / 2^n, W / 2^n)."""

    def __init__(self, in_channels: int, hidden: int, res_hidden: int, n_res: int,
                 out_channels: int, n_down: int = 3):
        super().__init__()
        chans = _stage_channels(hidden, n_down)
        layers, prev = [], in_channels
        for c in chans:
            # kernel 4, stride 2, padding 1 halves H and W exactly
            layers += [nn.Conv2d(prev, c, kernel_size=4, stride=2, padding=1), nn.ReLU()]
            prev = c
        layers += [
            nn.Conv2d(prev, hidden, kernel_size=3, padding=1),
            ResidualStack(hidden, res_hidden, n_res),
            nn.Conv2d(hidden, out_channels, kernel_size=1),
        ]
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)


class Decoder(nn.Module):
    """Latent (B, in_channels, h, w) -> image (B, out_channels, h * 2^n, w * 2^n) in [0, 1]."""

    def __init__(self, in_channels: int, hidden: int, res_hidden: int, n_res: int,
                 out_channels: int = 1, n_down: int = 3):
        super().__init__()
        chans = list(reversed(_stage_channels(hidden, n_down)))  # e.g. [128, 64, 32]
        layers = [
            nn.Conv2d(in_channels, hidden, kernel_size=3, padding=1),
            ResidualStack(hidden, res_hidden, n_res),
        ]
        prev = hidden
        for i, c in enumerate(chans[1:] + [out_channels]):
            layers.append(nn.ConvTranspose2d(prev, c, kernel_size=4, stride=2, padding=1))
            if i < n_down - 1:
                layers.append(nn.ReLU())
            prev = c
        self.net = nn.Sequential(*layers)

    def forward(self, z):
        return torch.sigmoid(self.net(z))  # images are normalised to [0, 1]


# --------------------------------------------------------------------------- #
# Vector quantiser
# --------------------------------------------------------------------------- #
class VectorQuantizerEMA(nn.Module):
    """Nearest-neighbour codebook lookup with EMA codebook updates.

    Args:
        num_embeddings: codebook size K.
        embedding_dim: code vector size D (must equal the encoder output channels).
        beta: commitment loss weight.
        decay: EMA decay for codebook statistics.
    """

    def __init__(self, num_embeddings: int = 512, embedding_dim: int = 64,
                 beta: float = 0.25, decay: float = 0.99, eps: float = 1e-5,
                 restart_patience: int = 50):
        super().__init__()
        self.K, self.D = num_embeddings, embedding_dim
        self.beta, self.decay, self.eps = beta, decay, eps
        self.restart_patience = restart_patience
        embed = torch.randn(num_embeddings, embedding_dim)
        # Buffers, not Parameters: they are updated by EMA, not by the optimiser,
        # but are still saved in the state_dict.
        self.register_buffer("embedding", embed)
        self.register_buffer("ema_cluster_size", torch.zeros(num_embeddings))
        self.register_buffer("ema_w", embed.clone())
        self.register_buffer("initialised", torch.tensor(False))
        self.register_buffer("restarts", torch.tensor(0))  # total dead-code restarts (for logging)
        # Consecutive training steps since each code was last selected
        self.register_buffer("steps_unused", torch.zeros(num_embeddings, dtype=torch.long))

    @torch.no_grad()
    def _random_rows(self, flat, n):
        """n random rows of flat (with replacement only if flat has fewer than n rows)."""
        if flat.shape[0] >= n:
            return flat[torch.randperm(flat.shape[0], device=flat.device)[:n]]
        return flat[torch.randint(0, flat.shape[0], (n,), device=flat.device)]

    @torch.no_grad()
    def _init_from_data(self, flat):
        """Data-dependent initialisation: codebook = K random encoder outputs."""
        embed = self._random_rows(flat, self.K)
        # Start each code at the usage it would have if all codes were used
        # equally, so new codes are not restarted before they get a chance.
        usage = flat.shape[0] / self.K
        self.embedding.copy_(embed)
        self.ema_cluster_size.fill_(usage)
        self.ema_w.copy_(embed * usage)  # ema_w / cluster_size == embedding
        self.initialised.fill_(True)

    @torch.no_grad()
    def _restart_dead_codes(self, flat, counts):
        """Move codes unused for more than restart_patience steps to random encoder outputs."""
        self.steps_unused = torch.where(counts > 0, torch.zeros_like(self.steps_unused), self.steps_unused + 1)
        dead = self.steps_unused > self.restart_patience
        n_dead = int(dead.sum())
        if n_dead == 0:
            return
        new = self._random_rows(flat, n_dead)
        usage = flat.shape[0] / self.K
        self.embedding[dead] = new
        self.ema_cluster_size[dead] = usage
        self.ema_w[dead] = new * usage
        self.steps_unused[dead] = 0
        self.restarts += n_dead

    def forward(self, z_e):
        B, D, H, W = z_e.shape
        # (B, D, H, W) -> (B*H*W, D); float32 for stable distances under AMP
        flat = z_e.permute(0, 2, 3, 1).reshape(-1, D).float()
        if self.training and not bool(self.initialised):
            self._init_from_data(flat.detach())

        # Squared Euclidean distance to every code: |x|^2 - 2 x.e + |e|^2
        dist = (flat.pow(2).sum(1, keepdim=True)
                - 2 * flat @ self.embedding.t()
                + self.embedding.pow(2).sum(1))
        indices = dist.argmin(dim=1)
        one_hot = F.one_hot(indices, self.K).type(flat.dtype)
        z_q = (one_hot @ self.embedding).view(B, H, W, D).permute(0, 3, 1, 2).contiguous()

        if self.training:
            with torch.no_grad():
                # Running count and running sum of encoder outputs per code
                counts = one_hot.sum(0)
                self.ema_cluster_size.mul_(self.decay).add_(counts, alpha=1 - self.decay)
                self.ema_w.mul_(self.decay).add_(one_hot.t() @ flat, alpha=1 - self.decay)
                # Laplace smoothing so unused codes never divide by zero
                n = self.ema_cluster_size.sum()
                size = (self.ema_cluster_size + self.eps) / (n + self.K * self.eps) * n
                self.embedding.copy_(self.ema_w / size.unsqueeze(1))
                self._restart_dead_codes(flat.detach(), counts)

        z_e32 = z_e.float()
        commitment = F.mse_loss(z_e32, z_q.detach())
        vq_loss = self.beta * commitment

        # Straight-through estimator: forward uses z_q, backward copies grads to z_e
        z_q = z_e32 + (z_q - z_e32).detach()

        # Perplexity = exp(entropy of code usage in this batch); K means all codes used equally
        avg_probs = one_hot.mean(0)
        perplexity = torch.exp(-(avg_probs * torch.log(avg_probs + 1e-10)).sum())
        return z_q.type_as(z_e), vq_loss, indices.view(B, H, W), perplexity

    def lookup(self, indices):
        """Code indices (B, H, W) -> quantised vectors (B, D, H, W)."""
        return self.embedding[indices].permute(0, 3, 1, 2).contiguous()


# --------------------------------------------------------------------------- #
# VQ-VAE (main model)
# --------------------------------------------------------------------------- #
class VQVAE(nn.Module):
    def __init__(self, in_channels: int = 1, hidden: int = 128, res_hidden: int = 64, n_res: int = 2,
                 num_embeddings: int = 512, embedding_dim: int = 64, n_down: int = 3,
                 beta: float = 0.25, decay: float = 0.99):
        super().__init__()
        self.n_down = n_down
        self.encoder = Encoder(in_channels, hidden, res_hidden, n_res, embedding_dim, n_down)
        self.quantizer = VectorQuantizerEMA(num_embeddings, embedding_dim, beta, decay)
        self.decoder = Decoder(embedding_dim, hidden, res_hidden, n_res, in_channels, n_down)

    def forward(self, x):
        """Returns (reconstruction, vq_loss, code indices, perplexity)."""
        z_q, vq_loss, indices, perplexity = self.quantizer(self.encoder(x))
        return self.decoder(z_q), vq_loss, indices, perplexity

    @torch.no_grad()
    def encode(self, x):
        """Images -> code grids (B, h, w) of integers in [0, K)."""
        _, _, indices, _ = self.quantizer(self.encoder(x))
        return indices

    def decode_indices(self, indices):
        """Code grids (B, h, w) -> images (B, 1, H, W)."""
        return self.decoder(self.quantizer.lookup(indices))

    def latent_shape(self, height: int, width: int) -> tuple:
        f = 2 ** self.n_down
        return height // f, width // f


# --------------------------------------------------------------------------- #
# VAE (baseline)
# --------------------------------------------------------------------------- #
class VAE(nn.Module):
    """Convolutional VAE with a spatial Gaussian latent on the same grid as the VQ-VAE."""

    def __init__(self, in_channels: int = 1, hidden: int = 128, res_hidden: int = 64, n_res: int = 2,
                 latent_channels: int = 8, n_down: int = 3):
        super().__init__()
        self.n_down, self.latent_channels = n_down, latent_channels
        # Encoder outputs mean and log-variance, hence 2 * latent_channels
        self.encoder = Encoder(in_channels, hidden, res_hidden, n_res, 2 * latent_channels, n_down)
        self.decoder = Decoder(latent_channels, hidden, res_hidden, n_res, in_channels, n_down)

    def forward(self, x):
        """Returns (reconstruction, mu, logvar). Uses the mean (no noise) in eval mode."""
        mu, logvar = self.encoder(x).chunk(2, dim=1)
        logvar = logvar.clamp(-30.0, 20.0)  # avoid exp overflow early in training
        if self.training:
            z = mu + torch.exp(0.5 * logvar) * torch.randn_like(mu)  # reparameterisation trick
        else:
            z = mu
        return self.decoder(z), mu, logvar

    @staticmethod
    def kl_divergence(mu, logvar):
        """KL(q(z|x) || N(0, I)), summed over latent dims, averaged over the batch."""
        return -0.5 * torch.sum(1 + logvar - mu.pow(2) - logvar.exp()) / mu.shape[0]

    @torch.no_grad()
    def sample(self, n: int, height: int, width: int, device):
        f = 2 ** self.n_down
        z = torch.randn(n, self.latent_channels, height // f, width // f, device=device)
        return self.decoder(z)


# --------------------------------------------------------------------------- #
# Gated PixelCNN prior over VQ-VAE codes
# --------------------------------------------------------------------------- #
class GatedMaskedConv2d(nn.Module):
    """One gated PixelCNN layer with vertical and horizontal stacks.

    Causality (raster order: rows top to bottom, columns left to right):
      * the vertical stack at row i only ever sees input rows < i;
      * the horizontal stack at (i, j) sees row i columns < j, plus the
        vertical stack (rows < i).
    Mask type 'A' (first layer) also excludes the current position itself;
    type 'B' (later layers) may include it, because by then it only carries
    information about earlier positions.
    """

    def __init__(self, mask_type: str, dim: int, kernel: int = 3, residual: bool = True):
        super().__init__()
        assert mask_type in ("A", "B") and kernel % 2 == 1
        self.mask_type, self.residual = mask_type, residual
        k2 = kernel // 2
        # Vertical: kernel (k2 + 1) x kernel covers the current row and k2 rows above
        self.vert = nn.Conv2d(dim, 2 * dim, (k2 + 1, kernel), padding=(k2, k2))
        self.vert_to_horiz = nn.Conv2d(2 * dim, 2 * dim, 1)
        # Horizontal: kernel 1 x (k2 + 1) covers the current column and k2 to the left
        self.horiz = nn.Conv2d(dim, 2 * dim, (1, k2 + 1), padding=(0, k2))
        self.horiz_out = nn.Conv2d(dim, dim, 1)

        # Type A: drop the current row from the vertical kernel and the current
        # column from the horizontal kernel.
        v_mask = torch.ones_like(self.vert.weight)
        h_mask = torch.ones_like(self.horiz.weight)
        if mask_type == "A":
            v_mask[:, :, -1] = 0
            h_mask[:, :, :, -1] = 0
        self.register_buffer("v_mask", v_mask)
        self.register_buffer("h_mask", h_mask)

    @staticmethod
    def _gate(x):
        a, b = x.chunk(2, dim=1)
        return torch.tanh(a) * torch.sigmoid(b)

    def forward(self, x_v, x_h):
        H, W = x_v.shape[-2:]
        # Padding adds k2 extra rows / columns at the end; keep the first H / W,
        # so output position i only depends on inputs at positions <= i.
        h_v = F.conv2d(x_v, self.vert.weight * self.v_mask, self.vert.bias,
                       padding=self.vert.padding)[:, :, :H, :]
        h_h = F.conv2d(x_h, self.horiz.weight * self.h_mask, self.horiz.bias,
                       padding=self.horiz.padding)[:, :, :, :W]

        out_v = self._gate(h_v)
        out_h = self.horiz_out(self._gate(h_h + self.vert_to_horiz(h_v)))
        if self.residual:
            out_h = out_h + x_h
        return out_v, out_h


class GatedPixelCNN(nn.Module):
    """Autoregressive prior p(codes) = prod_i p(c_i | c_<i) over a code grid."""

    def __init__(self, num_embeddings: int = 512, dim: int = 128, n_layers: int = 12):
        super().__init__()
        self.K = num_embeddings
        self.embedding = nn.Embedding(num_embeddings, dim)
        # First layer is type A and has no residual (the residual would leak the
        # current code straight to the output).
        layers = [GatedMaskedConv2d("A", dim, kernel=7, residual=False)]
        layers += [GatedMaskedConv2d("B", dim, kernel=3, residual=True) for _ in range(n_layers - 1)]
        self.layers = nn.ModuleList(layers)
        self.output = nn.Sequential(nn.ReLU(), nn.Conv2d(dim, 512, 1), nn.ReLU(), nn.Conv2d(512, num_embeddings, 1))

    def forward(self, codes):
        """codes (B, h, w) long -> logits (B, K, h, w)."""
        x = self.embedding(codes).permute(0, 3, 1, 2)
        x_v, x_h = x, x
        for layer in self.layers:
            x_v, x_h = layer(x_v, x_h)
        return self.output(x_h)

    @torch.no_grad()
    def sample(self, n: int, h: int, w: int, device, temperature: float = 1.0):
        """Generate n code grids one position at a time in raster order."""
        codes = torch.zeros(n, h, w, dtype=torch.long, device=device)
        for i in range(h):
            for j in range(w):
                logits = self.forward(codes)[:, :, i, j] / temperature
                codes[:, i, j] = torch.multinomial(F.softmax(logits, dim=-1), 1).squeeze(-1)
        return codes


# --------------------------------------------------------------------------- #
# Utilities and self-test
# --------------------------------------------------------------------------- #
def count_parameters(model: nn.Module) -> int:
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def check_pixelcnn_causality(model: GatedPixelCNN, h: int = 8, w: int = 6) -> bool:
    """Changing the code at one position must not change the logits at that
    position or any earlier position in raster order."""
    model.eval()
    torch.manual_seed(0)
    base = torch.randint(0, model.K, (1, h, w))
    ref = model(base)
    for pos in range(h * w):
        i, j = divmod(pos, w)
        changed = base.clone()
        changed[0, i, j] = (changed[0, i, j] + 1) % model.K
        diff = (model(changed) - ref).abs().amax(dim=1)[0].flatten()  # per position
        if diff[: pos + 1].max() > 1e-5:  # positions 0..pos must be unaffected
            return False
    return True


if __name__ == "__main__":
    torch.manual_seed(0)
    x = torch.rand(2, 1, 256, 128)

    vqvae = VQVAE()
    recon, vq_loss, idx, ppl = vqvae(x)
    assert recon.shape == x.shape and idx.shape == (2, 32, 16)
    assert vqvae.decode_indices(idx).shape == recon.shape
    print(f"VQVAE: params={count_parameters(vqvae):,} recon={tuple(recon.shape)} codes={tuple(idx.shape)} "
          f"vq_loss={vq_loss.item():.4f} perplexity={ppl.item():.1f}")
    # With data-dependent initialisation, an untrained model should already
    # spread positions over many codes (perplexity 1.0 would mean collapse).
    assert ppl.item() > 10, f"codebook collapse at initialisation (perplexity {ppl.item():.1f})"

    # Collapse-recovery test: feed near-identical vectors (everything maps to
    # one code) for longer than the patience, then check codes were restarted
    # and that varied inputs are again spread over many codes.
    vq = VectorQuantizerEMA(num_embeddings=64, embedding_dim=8, restart_patience=5)
    vq.train()
    vq(torch.randn(4, 8, 8, 8))                     # data-dependent init
    for _ in range(8):
        vq(0.01 * torch.randn(4, 8, 8, 8) + 5.0)    # collapsed encoder outputs
    for _ in range(3):
        _, _, _, ppl_after = vq(torch.randn(4, 8, 8, 8) * 5.0 + 5.0)
    print(f"Collapse recovery: restarts={int(vq.restarts)} perplexity_after={ppl_after.item():.1f}")
    assert int(vq.restarts) > 0 and ppl_after.item() > 10, "dead-code restart did not recover from collapse"

    vae = VAE()
    recon, mu, logvar = vae(x)
    assert recon.shape == x.shape and mu.shape == (2, 8, 32, 16)
    print(f"VAE:   params={count_parameters(vae):,} recon={tuple(recon.shape)} latent={tuple(mu.shape)} "
          f"kl={VAE.kl_divergence(mu, logvar).item():.2f} sample={tuple(vae.sample(2, 256, 128, 'cpu').shape)}")

    prior = GatedPixelCNN()
    logits = prior(idx)
    assert logits.shape == (2, 512, 32, 16)
    print(f"PixelCNN: params={count_parameters(prior):,} logits={tuple(logits.shape)}")

    small = GatedPixelCNN(num_embeddings=16, dim=16, n_layers=4)
    ok = check_pixelcnn_causality(small)
    print(f"PixelCNN causality check: {'PASS' if ok else 'FAIL'}")
    assert ok
    print("All self-tests passed.")
